use crate::oidc::{AccessToken, TokenProvider};
use reqwest::{Method, StatusCode};
use serde::{Deserialize, Serialize};
use std::error::Error;
use thiserror::Error as ThisError;
use url::Url;

/// Administrative account representation returned by razornd-identity.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
pub struct Account {
    pub username: String,
    pub enabled: bool,
}

/// Result returned when an account is created.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct CreatedAccount {
    pub username: String,
    pub enabled: bool,
    #[serde(default)]
    pub generated_password: Option<String>,
}

/// Fields accepted when creating an account. An omitted password is generated by the service.
#[derive(Clone, Debug, Default, Serialize, PartialEq, Eq)]
pub struct CreateAccountRequest {
    pub username: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub password: Option<String>,
    pub enabled: bool,
}

impl CreateAccountRequest {
    pub fn new(username: impl Into<String>) -> Self {
        Self {
            username: username.into(),
            password: None,
            enabled: true,
        }
    }
}

/// Optional fields accepted by the account update endpoint.
#[derive(Clone, Debug, Default, Serialize, PartialEq, Eq)]
pub struct UpdateAccountRequest {
    #[serde(skip_serializing_if = "Option::is_none")]
    pub password: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub enabled: Option<bool>,
}

#[derive(Debug, ThisError)]
pub enum RazorIdentityClientError<E>
where
    E: Error + 'static,
{
    #[error("Failed to obtain an access token: {0}")]
    TokenProvider(#[source] E),
    #[error("HTTP request failed: {0}")]
    Http(#[from] reqwest::Error),
    #[error("Invalid identity service URL: {0}")]
    Url(#[from] url::ParseError),
    #[error("Identity service returned HTTP {status}: {body}")]
    UnexpectedStatus { status: StatusCode, body: String },
    #[error("An account with this username already exists")]
    AccountAlreadyExists,
}

/// Client for razornd-identity's administrative account API.
pub struct RazorIdentityClient<P> {
    base_url: Url,
    token_provider: P,
    http_client: reqwest::Client,
}

impl<P: TokenProvider> RazorIdentityClient<P> {
    pub fn new(base_url: Url, token_provider: P, http_client: reqwest::Client) -> Self {
        Self {
            base_url,
            token_provider,
            http_client,
        }
    }

    /// Creates an account. The returned generated password is present only when the service
    /// generated the account's initial password.
    pub async fn create_account(
        &self,
        request: &CreateAccountRequest,
    ) -> Result<CreatedAccount, RazorIdentityClientError<P::Error>> {
        let response = self
            .authorized_request(Method::POST, self.accounts_url()?)
            .await?
            .json(request)
            .send()
            .await?;

        if response.status() == StatusCode::CONFLICT {
            return Err(RazorIdentityClientError::AccountAlreadyExists);
        }
        let response = self.expect_status(response, StatusCode::CREATED).await?;
        Ok(response.json().await?)
    }

    /// Gets an account, returning `None` when no matching username exists.
    pub async fn get_account(
        &self,
        username: &str,
    ) -> Result<Option<Account>, RazorIdentityClientError<P::Error>> {
        let response = self
            .authorized_request(Method::GET, self.account_url(username)?)
            .await?
            .send()
            .await?;
        if response.status() == StatusCode::NOT_FOUND {
            return Ok(None);
        }
        let response = self.expect_status(response, StatusCode::OK).await?;
        Ok(Some(response.json().await?))
    }

    /// Updates an account's password and/or enabled state.
    pub async fn update_account(
        &self,
        username: &str,
        request: &UpdateAccountRequest,
    ) -> Result<Option<Account>, RazorIdentityClientError<P::Error>> {
        let response = self
            .authorized_request(Method::PATCH, self.account_url(username)?)
            .await?
            .json(request)
            .send()
            .await?;
        if response.status() == StatusCode::NOT_FOUND {
            return Ok(None);
        }
        let response = self.expect_status(response, StatusCode::OK).await?;
        Ok(Some(response.json().await?))
    }

    /// Disables an account without deleting it. Returns `false` if it does not exist.
    pub async fn disable_account(
        &self,
        username: &str,
    ) -> Result<bool, RazorIdentityClientError<P::Error>> {
        let response = self
            .authorized_request(Method::DELETE, self.account_url(username)?)
            .await?
            .send()
            .await?;
        if response.status() == StatusCode::NOT_FOUND {
            return Ok(false);
        }
        self.expect_status(response, StatusCode::NO_CONTENT).await?;
        Ok(true)
    }

    async fn authorized_request(
        &self,
        method: Method,
        url: Url,
    ) -> Result<reqwest::RequestBuilder, RazorIdentityClientError<P::Error>> {
        let token = self.access_token().await?;
        Ok(self
            .http_client
            .request(method, url)
            .bearer_auth(token.expose_secret()))
    }

    async fn expect_status(
        &self,
        response: reqwest::Response,
        expected: StatusCode,
    ) -> Result<reqwest::Response, RazorIdentityClientError<P::Error>> {
        if response.status() == expected {
            return Ok(response);
        }
        let status = response.status();
        let body = response.text().await?;
        Err(RazorIdentityClientError::UnexpectedStatus { status, body })
    }

    fn accounts_url(&self) -> Result<Url, RazorIdentityClientError<P::Error>> {
        Ok(self.base_url.join("api/admin/accounts")?)
    }

    fn account_url(&self, username: &str) -> Result<Url, RazorIdentityClientError<P::Error>> {
        let mut url = self.accounts_url()?;
        url.path_segments_mut()
            .expect("HTTP(S) service URLs support path segments")
            .push(username);
        Ok(url)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use async_trait::async_trait;
    use std::convert::Infallible;
    use wiremock::{
        Mock, MockServer, ResponseTemplate,
        matchers::{bearer_token, body_json, method, path},
    };

    struct TestTokenProvider;

    #[async_trait]
    impl TokenProvider for TestTokenProvider {
        type Error = Infallible;

        async fn access_token(&self) -> Result<AccessToken, Self::Error> {
            Ok(AccessToken::new("test-token".to_owned()))
        }
    }

    fn client(server: &MockServer) -> RazorIdentityClient<TestTokenProvider> {
        RazorIdentityClient::new(
            Url::parse(&server.uri()).unwrap(),
            TestTokenProvider,
            reqwest::Client::new(),
        )
    }

    #[tokio::test]
    async fn creates_account_with_bearer_token_and_returns_generated_password() {
        let server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/api/admin/accounts"))
            .and(bearer_token("test-token"))
            .and(body_json(serde_json::json!({
                "username": "alice",
                "enabled": true
            })))
            .respond_with(ResponseTemplate::new(201).set_body_json(serde_json::json!({
                "username": "alice",
                "enabled": true,
                "generatedPassword": "generated-secret"
            })))
            .expect(1)
            .mount(&server)
            .await;

        let created = client(&server)
            .create_account(&CreateAccountRequest::new("alice"))
            .await
            .unwrap();
        assert_eq!(created.username, "alice");
        assert_eq!(
            created.generated_password.as_deref(),
            Some("generated-secret")
        );
    }

    #[tokio::test]
    async fn gets_updates_and_disables_accounts() {
        let server = MockServer::start().await;
        Mock::given(method("GET"))
            .and(path("/api/admin/accounts/alice%20smith"))
            .and(bearer_token("test-token"))
            .respond_with(ResponseTemplate::new(200).set_body_json(serde_json::json!({
                "username": "alice smith",
                "enabled": true
            })))
            .mount(&server)
            .await;
        Mock::given(method("PATCH"))
            .and(path("/api/admin/accounts/alice%20smith"))
            .and(bearer_token("test-token"))
            .and(body_json(serde_json::json!({ "enabled": false })))
            .respond_with(ResponseTemplate::new(200).set_body_json(serde_json::json!({
                "username": "alice smith",
                "enabled": false
            })))
            .mount(&server)
            .await;
        Mock::given(method("DELETE"))
            .and(path("/api/admin/accounts/alice%20smith"))
            .and(bearer_token("test-token"))
            .respond_with(ResponseTemplate::new(204))
            .mount(&server)
            .await;

        let client = client(&server);
        assert_eq!(
            client
                .get_account("alice smith")
                .await
                .unwrap()
                .unwrap()
                .enabled,
            true
        );
        assert_eq!(
            client
                .update_account(
                    "alice smith",
                    &UpdateAccountRequest {
                        enabled: Some(false),
                        ..Default::default()
                    }
                )
                .await
                .unwrap()
                .unwrap()
                .enabled,
            false
        );
        assert!(client.disable_account("alice smith").await.unwrap());
    }

    #[tokio::test]
    async fn maps_not_found_and_conflict_responses() {
        let server = MockServer::start().await;
        Mock::given(method("GET"))
            .and(path("/api/admin/accounts/missing"))
            .respond_with(ResponseTemplate::new(404))
            .mount(&server)
            .await;
        Mock::given(method("DELETE"))
            .and(path("/api/admin/accounts/missing"))
            .respond_with(ResponseTemplate::new(404))
            .mount(&server)
            .await;
        Mock::given(method("POST"))
            .and(path("/api/admin/accounts"))
            .respond_with(ResponseTemplate::new(409))
            .mount(&server)
            .await;

        let client = client(&server);
        assert!(client.get_account("missing").await.unwrap().is_none());
        assert!(!client.disable_account("missing").await.unwrap());
        assert!(matches!(
            client
                .create_account(&CreateAccountRequest::new("duplicate"))
                .await,
            Err(RazorIdentityClientError::AccountAlreadyExists)
        ));
    }
}

impl<P: TokenProvider> RazorIdentityClient<P> {
    async fn access_token(&self) -> Result<AccessToken, RazorIdentityClientError<P::Error>> {
        self.token_provider
            .access_token()
            .await
            .map_err(RazorIdentityClientError::TokenProvider)
    }
}
